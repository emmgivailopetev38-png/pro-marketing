export function verticalMetadata(slug: Vertical): Metadata {
  const v = VERTICALS[slug];
  const title = SEO_TITLE[slug];
  return {
    title,
    description: v.desc,
    alternates: { canonical: `/demo/${slug}` },
    openGraph: {
      type: "website",
      locale: "bg_BG",
      url: `/demo/${slug}`,
      siteName: "ProMarketing",
      title,
      description: v.desc,
    },
    twitter: { card: "summary_large_image", title, description: v.desc },
    // ⚠️ Досега тук стоеше robots:{index:false} и деветте браншови демота
    // бяха невидими за Google. Точно те обаче са „браншовите страници“,
    // които печелят търсения като „AI за счетоводна кантора“ — заявка с
    // почти нулева конкуренция на български. Пусната е индексацията.
    // Връща се с един ред, ако демотата трябва да останат само за срещи.
    robots: { index: true, follow: true },
  };
}

