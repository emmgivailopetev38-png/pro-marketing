-- Комисионата на продавача (26.09.2026).
-- Ивайло: „тя е продавач и за нея нещата са десет процента комисиона от затворена сделка“.
-- Правило по роля за всеки вид услуга: 10 % от сумата на сделката, веднъж. Общите
-- правила (200 € / 150 € / 10 % месечно) остават за останалите роли. Месечното
-- начисление пропуска роля с правило „от сделката“ (monthlyRuleFor) — продавачът няма
-- месечна комисионна. Само добавя редове: старият код ги чете като правила по роля.

insert into public.commission_rules (service_type, label, kind, value, basis, role, notes)
select v.service_type, v.label, 'percent', 10, 'deal', 'sales', 'Продавач: 10 % от затворената сделка, веднъж (26.09.2026).'
from (values
  ('marketing',   'Продавач · Маркетинг · 10 % от сделката'),
  ('crm_support', 'Продавач · Поддръжка · 10 % от сделката'),
  ('website',     'Продавач · Уебсайт · 10 % от сделката'),
  ('crm_build',   'Продавач · CRM изграждане · 10 % от сделката'),
  ('automation',  'Продавач · AI автоматизация · 10 % от сделката'),
  ('voice_agent', 'Продавач · Гласов агент · 10 % от сделката'),
  ('training',    'Продавач · Обучение / менторство · 10 % от сделката'),
  ('other',       'Продавач · Друг проект · 10 % от сделката')
) as v(service_type, label)
where not exists (
  select 1 from public.commission_rules r where r.role = 'sales' and r.service_type = v.service_type
);
