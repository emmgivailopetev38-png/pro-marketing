alter table public.offers
  add column if not exists number integer generated by default as identity,
  add column if not exists token text,
  add column if not exists template_key text,
  add column if not exists items jsonb not null default '[]'::jsonb,
  add column if not exists content jsonb not null default '{}'::jsonb,
  add column if not exists discount numeric(12, 2),
  add column if not exists discount_note text,
  add column if not exists vat_mode text not null default 'incl',
  add column if not exists owner_id uuid references public.team_members(id) on delete set null,
  add column if not exists created_by text;

alter table public.offers drop constraint if exists offers_vat_mode_check;
alter table public.offers
  add constraint offers_vat_mode_check check (vat_mode in ('incl', 'excl', 'none'));

create unique index if not exists offers_token_idx on public.offers (token) where token is not null;
create unique index if not exists offers_number_idx on public.offers (number);

create table if not exists public.offer_templates (
  id uuid primary key default gen_random_uuid(),
  key text not null unique,
  name text not null,
  description text,
  items jsonb not null default '[]'::jsonb,
  content jsonb not null default '{}'::jsonb,
  vat_mode text not null default 'incl' check (vat_mode in ('incl', 'excl', 'none')),
  active boolean not null default true,
  sort_order int not null default 0,
  updated_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

drop trigger if exists offer_templates_set_updated_at on public.offer_templates;
create trigger offer_templates_set_updated_at before update on public.offer_templates
  for each row execute function public.set_updated_at();

alter table public.offer_templates enable row level security;
