import { describe, it, expect } from "vitest";
import { parseWhen, fromSofia, speakDate } from "./when";

/** Сряда, 26 август 2026, 12:00 софийско време. */
const NOW = fromSofia(2026, 8, 26, 12, 0);
const sofia = (d: Date) =>
  new Intl.DateTimeFormat("sv-SE", {
    timeZone: "Europe/Sofia",
    year: "numeric", month: "2-digit", day: "2-digit",
    hour: "2-digit", minute: "2-digit", hour12: false,
  }).format(d).replace(" ", "T");

const at = (raw: string, defaultHour?: number) => {
  const r = parseWhen(raw, { now: NOW, ...(defaultHour ? { defaultHour } : {}) });
  return r ? sofia(r.date) : null;
};

describe("parseWhen", () => {
  it("чете ISO дата като софийско време, не като UTC", () => {
    // Иначе „15:00" се записва като 18:00 през лятото.
    expect(at("2026-09-01T15:00")).toBe("2026-09-01T15:00");
  });

  it("уважава изрична зона, когато има такава", () => {
    expect(at("2026-09-01T12:00:00Z")).toBe("2026-09-01T15:00"); // UTC+3 лятно
  });

  it("гола ISO дата получава часа по подразбиране", () => {
    expect(at("2026-09-01", 9)).toBe("2026-09-01T09:00");
  });

  it("разбира днес, утре, вдругиден", () => {
    expect(at("днес")).toBe("2026-08-26T10:00");
    expect(at("утре")).toBe("2026-08-27T10:00");
    expect(at("вдругиден")).toBe("2026-08-28T10:00");
  });

  it("разбира „след N дни/седмици/месеца“ и с думи, и с цифри", () => {
    expect(at("след 3 дни")).toBe("2026-08-29T10:00");
    expect(at("след два дни")).toBe("2026-08-28T10:00");
    expect(at("след седмица")).toBe("2026-09-02T10:00");
    expect(at("след месец")).toBe("2026-09-26T10:00");
  });

  it("другата седмица без ден е понеделник", () => {
    expect(at("другата седмица")).toBe("2026-08-31T10:00");
  });

  it("ден от седмицата гледа напред, не назад", () => {
    expect(at("в петък")).toBe("2026-08-28T10:00");
    expect(at("в понеделник")).toBe("2026-08-31T10:00");
    // Сряда, казана в сряда, значи следващата сряда — не днес.
    expect(at("в сряда")).toBe("2026-09-02T10:00");
  });

  it("хваща часа заедно с деня", () => {
    expect(at("утре в 15:30")).toBe("2026-08-27T15:30");
    expect(at("в петък в три следобед")).toBe("2026-08-28T15:00");
    expect(at("утре сутринта")).toBe("2026-08-27T09:00");
    expect(at("утре вечерта")).toBe("2026-08-27T18:00");
  });

  it("„в 4“ в работен контекст е следобед, не 4 сутринта", () => {
    expect(at("утре в 4")).toBe("2026-08-27T16:00");
    expect(at("утре в 4 сутринта")).toBe("2026-08-27T04:00");
  });

  it("разбира дати с точка и с име на месец", () => {
    expect(at("15.09")).toBe("2026-09-15T10:00");
    expect(at("15.09.2026 в 11:00")).toBe("2026-09-15T11:00");
    expect(at("на 3 септември")).toBe("2026-09-03T10:00");
  });

  it("минал месец без година се тълкува като догодина", () => {
    // 3 март 2026 вече е минал → срещата е за 2027, не в миналото.
    expect(at("на 3 март")).toBe("2027-03-03T10:00");
  });

  it("връща null за неразбираемо, вместо да измисли дата", () => {
    expect(parseWhen("ъъъ някога", { now: NOW })).toBeNull();
    expect(parseWhen("", { now: NOW })).toBeNull();
  });

  it("самостоятелен час без ден пада днес", () => {
    expect(at("в 17:00")).toBe("2026-08-26T17:00");
  });
});

describe("speakDate", () => {
  it("чете се на български", () => {
    const s = speakDate(fromSofia(2026, 8, 27, 15, 0));
    expect(s).toContain("август");
    expect(s).toContain("15");
  });
});

describe("parseWhen · поправки след живия тест", () => {
  it("„другата седмица във вторник“ е вторник ОТ СЛЕДВАЩАТА седмица", () => {
    // Сряда, 26.08 → вторникът другата седмица е 01.09, а не утрешният 27.08.
    expect(at("другата седмица във вторник")).toBe("2026-09-01T10:00");
    expect(at("следващата седмица в петък")).toBe("2026-09-04T10:00");
  });

  it("разпознава минали дни, за да може срещата да бъде отказана", () => {
    expect(at("вчера в 10")).toBe("2026-08-25T10:00");
    expect(at("онзи ден")).toBe("2026-08-24T10:00");
  });
});
