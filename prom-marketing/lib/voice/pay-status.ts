/**
 * Какво казва агентът според състоянието на линка за споразумението.
 *
 * Чисти изречения без база — за да се тестват и за да звучат еднакво от
 * `pay-status` рута и от промпта. Състоянията са тези на офертата в CRM-а:
 *   accepted → платено (webhook-ът на Stripe я е приел)
 *   viewed   → отворил е линка, но още не е платил
 *   sent     → линкът е на имейла, нищо друго
 *   draft    → Stripe не е бил готов — Ивайло праща линка ръчно
 *   none     → няма изпратен линк към този човек
 */
export type PayStatus = "paid" | "opened" | "sent" | "manual" | "none";

export function payStatusFromOffer(status: string | null | undefined): PayStatus {
  switch (status) {
    case "accepted":
      return "paid";
    case "viewed":
      return "opened";
    case "sent":
      return "sent";
    case "draft":
      return "manual";
    default:
      return "none";
  }
}

