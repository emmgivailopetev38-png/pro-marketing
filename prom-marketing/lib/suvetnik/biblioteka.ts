export function vazrazhenieOt(tekst: string): Veriga | undefined {
  const t = tekst.toLowerCase();
  return VAZRAZHENIYA.find((v) => v.signali.some((s) => t.includes(s)));
}

/** Текстът на библиотеката за системния промпт. */
export function bibliotekaZaPrompt(): string {
  const v = VAZRAZHENIYA.map((x) =>
    [
      `### ${x.ime} [${x.id}]`,
      `Под него: ${x.otdolu}`,
      ...x.hodove.map((h, i) => `${i + 1}. (${h.ton}${h.kak ? `, ${h.kak}` : ""}) ${h.kazhi}${h.zashto ? ` — ${h.zashto}` : ""}`),
    ].join("\n"),
  ).join("\n\n");
  const p = (Object.keys(PREVENCIA) as PrevenciaId[])
    .map((id) => `- ${id} — кога: ${PREVENCIA[id].koga}\n${PREVENCIA[id].repliki.map((r) => `  · ${r}`).join("\n")}`)
    .join("\n");
  return [
    "## ВЕРИГИТЕ ЗА ВЪЗРАЖЕНИЯ (дословно от схемите на Георги — давай ПО ЕДНА стъпка)",
    v,
    "## ПРЕВЕНЦИЯТА (обира се преди ползите и цената)",
    p,
    "## ПРЕРАМКИРАНЕ",
    PRERAMKIRANE.map((r) => `- ${r}`).join("\n"),
    "## ЗАТВАРЯНЕ И ПЛАЩАНЕ",
    `Изречението: „${ZATVARYANE.izrechenieto}“`,
    ...ZATVARYANE.plashtane.map((r) => `- ${r}`),
    ...ZATVARYANE.pravila.map((r) => `- ${r}`),
  ].join("\n\n");
}

