import { describe, expect, it } from "vitest";
import { DEFAULT_TEMPLATES, MODULES } from "./katalog";
import { isVerb2, kamVie } from "./vie";

/** Остатък от „ти“ в текст на „Вие“ — думите, които не бива да оцелеят. */
const TI_LEFT = /(?<![\p{L}])(ти|теб|тебе|твой|твоя|твоят|твоята|твоето|твоите|твое|твои|докъде си|когато си)(?![\p{L}])/iu;
const verbLeft = (s: string) => [...s.matchAll(/[\p{L}]+/gu)].map((m) => m[0]).filter((w) => isVerb2(w));

describe("ти → Вие", () => {
  it("превръща типичните изрази от каталога", () => {
    expect(kamVie("Конкретен процес в бизнеса ти — построен от нас и обяснен на екипа")).toBe("Конкретен процес в бизнеса Ви — построен от нас и обяснен на екипа");
    expect(kamVie("Казваш „да“ — по телефона, във Viber или с отговор на този имейл.")).toBe("Казвате „да“ — по телефона, във Viber или с отговор на този имейл.");
    expect(kamVie("строим на екран, ти повтаряш за своя бизнес")).toBe("строим на екран, Вие повтаряте за своя бизнес");
    expect(kamVie("Нито едно запитване без обаждане — и срещи в календара, без ти да звъниш.")).toBe("Нито едно запитване без обаждане — и срещи в календара, без Вие да звъните.");
    expect(kamVie("AI, който ти строи автоматизациите — казваш какво искаш, той го прави")).toBe("AI, който Ви строи автоматизациите — казвате какво искате, той го прави");
    expect(kamVie("записите и обобщенията ги получаваш ти")).toBe("записите и обобщенията ги получавате Вие");
    expect(kamVie("Всеки урок се вижда в твоя профил — ти и ние знаем докъде си.")).toBe("Всеки урок се вижда във Вашия профил — Вие и ние знаем докъде сте.");
    expect(kamVie("AI-ят, с който сам си строиш CRM-а")).toBe("AI-ят, с който сами си строите CRM-а");
    expect(kamVie("и умението да ги променяш сам.")).toBe("и умението да ги променяте сами.");
    expect(kamVie("система, която работи и когато теб те няма")).toBe("система, която работи и когато Вас Ви няма");
    expect(kamVie("надграждаш към обучението, когато си готов")).toBe("надграждате към обучението, когато сте готови");
    expect(kamVie("Абонаментите — на твое име; бюджетът е твой.")).toBe("Абонаментите — на Ваше име; бюджетът е Ваш.");
  });
  it("не пипа текст на „Вие“, числата с член и третото лице", () => {
    const vie = "Благодаря за разговора с Георги. Гласовият агент ще приема поръчки за Вас; 4-те месеца, бизнесът върви сам — те го виждат.";
    expect(kamVie(vie)).toBe(vie);
    expect(kamVie("Нашият екип и Вашият бизнес")).toBe("Нашият екип и Вашият бизнес");
  });
  it("в каталога и шаблоните не остава „ти“ след превръщането", () => {
    const texts: string[] = [];
    for (const m of MODULES) texts.push(m.title, m.subtitle, ...m.bullets, m.outcome ?? "", ...(m.not_included ?? []), m.setup_label ?? "");
    for (const t of DEFAULT_TEMPLATES) {
      const c = t.content;
      texts.push(c.intro ?? "", c.outcome ?? "", c.ps ?? "", ...(c.next_steps ?? []), ...(c.terms ?? []));
      for (const i of t.items) texts.push(i.subtitle ?? "", ...i.bullets, i.outcome ?? "", i.note ?? "");
    }
    const left = texts
      .map((x) => kamVie(x))
      .filter((x) => TI_LEFT.test(x) || verbLeft(x).length > 0);
    expect(left).toEqual([]);
  });
});
