/** 1 234 567 → „1 234 567“ (интервал за хилядите, както се пише у нас). */
export function chislo(n: number): string {
  const s = Math.round(n).toString();
  return s.replace(/\B(?=(\d{3})+(?!\d))/g, " ");
}

/** Колко броя по тази цена правят месечната цел. */
export function zaCelta(cena: number, cel: number = MESECHNA_CEL): number {
  if (!(cena > 0)) return 0;
  return Math.ceil(cel / cena);
}

/** Колко на работен ден са N продажби на месец (закръглено до 0,1). */
export function naDen(broiNaMesec: number): number {
  return Math.round((broiNaMesec / RABOTNI_DNI) * 10) / 10;
}

export type Red = {
  cena: Cena;
  sumi: { broi: number; suma: number }[];
  zaCelta: number;
};

/** Таблицата „една, пет, десет менторски“ + колко трябват за 300 000 €/мес. */
export function tablica(ceni: Cena[] = MENTORSKI, broiki: readonly number[] = BROYKI): Red[] {
  return ceni.map((cena) => ({
    cena,
    sumi: broiki.map((broi) => ({ broi, suma: broi * cena.value })),
    zaCelta: zaCelta(cena.value),
  }));
}
