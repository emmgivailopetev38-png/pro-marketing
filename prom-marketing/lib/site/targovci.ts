/** 10 % от сумата, закръглено до цента. */
export function komisiona(suma: number): number {
  return Math.round(suma * KOMISIONA * 100) / 100;
}

/**
 * „7 900 €“, „19,90 €“ — както е в стълбата. Ръчно, защото bg-BG в Intl не
 * разделя четирицифрените („7900“), а сървърът и браузърът трябва да пишат еднакво.
 */
export function evro(suma: number): string {
  const centove = Math.round(Math.abs(suma) * 100);
  const cyalo = Math.floor(centove / 100);
  const ostatak = centove % 100;
  const hilyadi = String(cyalo).replace(/\B(?=(\d{3})+(?!\d))/g, " ");
  const znak = suma < 0 ? "−" : "";
  return `${znak}${hilyadi}${ostatak ? `,${String(ostatak).padStart(2, "0")}` : ""} €`;
}

export type Izbor = Record<string, number>;

/**
 * Сметката на калкулатора: колко сделки от всяка услуга на месец →
 * еднократните комисионни за месеца и месечните, които се трупат с всеки нов
 * клиент на абонамент (докато клиентите плащат).
 */
export function smetka(izbor: Izbor, meseci = 6): { ednokratno: number; mesechnoNaMesec: number; prezMesec: number } {
  let ednokratno = 0;
  let mesechnoNaMesec = 0;
  for (const u of USLUGI) {
    const n = Math.max(0, Math.floor(izbor[u.id] ?? 0));
    ednokratno += n * komisiona(u.cena);
    mesechnoNaMesec += n * komisiona(u.mesechno);
  }
  ednokratno = Math.round(ednokratno * 100) / 100;
  mesechnoNaMesec = Math.round(mesechnoNaMesec * 100) / 100;
  // В месец N се плащат еднократните от този месец + абонаментите на всички довели до момента.
  const prezMesec = Math.round((ednokratno + mesechnoNaMesec * meseci) * 100) / 100;
  return { ednokratno, mesechnoNaMesec, prezMesec };
}

