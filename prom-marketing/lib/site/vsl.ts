export function isVslSlug(v: unknown): v is VslSlug {
  return v === "biznes" || v === "pari-s-ai";
}

/** „?ime=Иван“ → „Иван“; всичко подозрително → null. */
export function cleanName(raw: string | string[] | undefined): string | null {
  const v = (Array.isArray(raw) ? raw[0] : raw)?.trim();
  if (!v || v.length > 30) return null;
  return /^[\p{L}][\p{L} .'-]{0,29}$/u.test(v) ? v : null;
}

/** 609 → „10:09“. */
export function fmtTime(sec: number): string {
  const s = Math.max(0, Math.round(sec));
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, "0")}`;
}

/**
 * Отговорите → текстът, който стига до Георги (и в картона). Само попълнените,
 * в реда на въпросите; непознати ключове и празни се пропускат.
 */
export function answersText(c: VslContent, who: { name: string; phone: string }, answers: Record<string, string>): string {
  const lines = c.questions
    .map((q) => {
      const a = (answers[q.key] ?? "").trim();
      return a ? `• ${q.label}\n  ${a}` : null;
    })
    .filter((x): x is string => !!x);
  return [
    `📝 Преди срещата · видео „${c.name}“`,
    `${who.name} · ${who.phone}`,
    "",
    lines.length ? lines.join("\n") : "(без отговори — само името и телефона)",
  ].join("\n");
}
