/**
 * Текстовете, с които се затопля лийд по месинджър.
 *
 * Съобщението в чат не е къс имейл. То се чете за три секунди на телефона, в
 * движение, и има точно една задача: да даде повод човекът да си избере час.
 * Затова е кратко, започва с името и завършва с линк — никога с въпрос, на
 * който трябва да се отговаря писмено.
 *
 * Тонът е този от правилата: топло начало, ползата напред, конкретна покана.
 * Нищо, което ни прави натрапници — без „да не Ви губя времето", без
 * „извинявам се, че пиша", без „опитах да Ви търся няколко пъти".
 *
 * Български кавички вътре в низ с двойни кавички чупят парсера — затова
 * всичко тук е в backticks.
 */

import { firstName, VERTICAL_DEMOS } from "@/lib/email/sequence-layout";
import type { WarmthBand } from "./warmth";

export interface MessageCtx {
  full_name: string | null;
  company: string | null;
  /** Лентата решава повода: топлият получава референция, недокоснатият — нова тема. */
  band: WarmthBand;
  /** Какво е направил човекът, с малка буква: `отвори офертата`. */
  top_reason: string | null;
  /** Личният линк към /z/<код>. */
  link: string;
  /** Вертикалът, ако го знаем — `slug` от VERTICAL_DEMOS. */
  vertical?: string | null;
  /** Обръщение на „Вие". По подразбиране е на „ти". */
  formal?: boolean;
}

/** Обръщението — първо име, ако го имаме; иначе фирмата; иначе нищо. */
function greeting(ctx: MessageCtx): string {
  const name = firstName(ctx.full_name);
  const hi = ctx.formal ? `Здравейте` : `Здравей`;
  if (name) return `${hi}, ${name}`;
  if (ctx.company) return `${hi} от ${ctx.company}`;
  return hi;
}

/** Ползата за неговия бранш — общата, ако вертикалът е непознат. */
function verticalLine(vertical: string | null | undefined): string {
  const v = VERTICAL_DEMOS.find((d) => d.slug === vertical);
  return v ? v.line : `рекламите, запитванията и офертите вървят на едно място`;
}

/**
 * Сглобява съобщението.
 *
 * Всеки вариант е три абзаца: повод → полза → покана с линк. Разделени с
 * празен ред, защото месинджърите слепват изреченията в стена от текст.
 */
export function warmMessage(ctx: MessageCtx): string {
  const hi = greeting(ctx);
  const sign = `— Ивайло от ProMarketing`;

  switch (ctx.band) {
    // Вече е вдигнал ръка, но не вдига телефона. Поводът е неговото действие,
    // а тонът дава контрола на него — не се оправдаваме за обаждането.
    case "hot": {
      const seen = ctx.top_reason ? `Видях, че ${ctx.formal ? formalVerb(ctx.top_reason) : ctx.top_reason}.` : ``;
      const call = ctx.formal
        ? `Звъннах, но явно съм уцелил лош момент.`
        : `Звъннах, но явно улучих лош момент.`;
      const pick = ctx.formal
        ? `Изберете си час, когато Ви е удобно — петнайсет минути стигат:`
        : `Избери си час, когато ти е удобно — петнайсет минути стигат:`;
      return [`${hi} ${sign}.`, [seen, call].filter(Boolean).join(` `), `${pick}\n${ctx.link}`].join(`\n\n`);
    }

    // Има сигнал, но слаб. Референцията е кратка, а поканата поема въпроса,
    // който човекът и без това си задава.
    case "warm": {
      const seen = ctx.top_reason
        ? `Видях, че ${ctx.formal ? formalVerb(ctx.top_reason) : ctx.top_reason} — благодаря!`
        : `Радвам се на интереса!`;
      const offer = ctx.formal
        ? `Ако е останал въпрос, най-бързо се изчиства на екран.`
        : `Ако ти е останал въпрос, най-бързо се изчиства на екран.`;
      const pick = ctx.formal ? `Петнайсет минути, изберете си час:` : `Петнайсет минути, избери си час:`;
      return [`${hi} ${sign}.`, `${seen} ${offer}`, `${pick}\n${ctx.link}`].join(`\n\n`);
    }

    // Получавал е писма и не е реагирал. Значи писмото не е стигнало или не е
    // било за него — поводът тук е конкретната полза, не поредното напомняне.
    case "cold": {
      const line = verticalLine(ctx.vertical);
      const lead = ctx.formal
        ? `Нещо съвсем конкретно за Вашия бранш: ${line}.`
        : `Нещо съвсем конкретно за твоя бранш: ${line}.`;
      const pick = ctx.formal
        ? `Ако звучи интересно — петнайсет минути на екран и ще Ви кажа какво точно бих направил при Вас:`
        : `Ако ти звучи интересно — петнайсет минути на екран и ще ти кажа какво точно бих направил при теб:`;
      return [`${hi} ${sign}.`, lead, `${pick}\n${ctx.link}`].join(`\n\n`);
    }

    // Никога не е докосван, и обикновено е отпреди месеци. „Оставихте
    // запитване" вече не се връзва — затова поводът е нов и е наш, не негов.
    case "untouched": {
      const lead = `Пуснахме гласов AI агент, който вдига телефона на фирмата и записва часове сам, докато ${ctx.formal ? `сте` : `си`} зает${ctx.formal ? `и` : ``}.`;
      const pick = ctx.formal
        ? `Чуйте го как звучи — и ако Ви хареса, часът се избира на същото място:`
        : `Чуй го как звучи — и ако ти хареса, часът се избира на същото място:`;
      return [`${hi} ${sign}.`, lead, `${pick}\n${ctx.link}`].join(`\n\n`);
    }
  }
}

/**
 * Учтивата форма на глагола в причината.
 *
 * Причините идват от `SIGNAL_LABEL` в трето лице единствено число
 * (`отвори офертата`) — при „Вие" трябва второ лице множествено
 * (`сте отворили офертата`). Кратък речник, защото сигналите са малко и
 * известни; непознатото се връща както е, вместо да се гадае.
 */
const FORMAL_VERB: Record<string, string> = {
  [`записа си час`]: `сте си записали час`,
  [`записа си час през агента`]: `сте си записали час през агента`,
  [`отговори на имейл`]: `сте отговорили на имейл`,
  [`говори с гласовия агент`]: `сте говорили с гласовия агент`,
  [`отвори офертата`]: `сте отворили офертата`,
  [`отвори личния линк`]: `сте отворили линка`,
  [`отвори гласовия агент`]: `сте отворили гласовия агент`,
  [`попълни форма на сайта`]: `сте попълнили форма на сайта`,
  [`остави данни в реклама`]: `сте оставили данни в рекламата`,
};

export function formalVerb(reason: string): string {
  return FORMAL_VERB[reason] ?? reason;
}
