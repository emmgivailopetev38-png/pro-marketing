/**
 * СТУДЕНАТА ПОРЕДИЦА — писмата към лийд, който още не е говорил с нас.
 *
 * Тонът е по правилото на Ивайло: така, както приятел ти показва нещо готино,
 * без напрежение и без официалщина. Никакво „гоня", никакви извинения, че
 * пишем, никакво самопринизяване. Всеки имейл води към услуга с конкретна
 * следваща стъпка и носи всички контакти — човекът никога не трябва да търси
 * как да се свърже.
 *
 * Две входни точки, един и същ път след първото писмо:
 *   • `LEAD_SEQUENCE` — лийд от Meta реклама или от формата на сайта. Първото
 *     писмо му показва демотата.
 *   • `VOICE_LEAD_SEQUENCE` — лийд от рекламата за гласовия агент (`/glas`).
 *     Той вече е ЧУЛ агента; първото писмо тръгва от този разговор, а не от
 *     нулата. Оттам нататък писмата са същите.
 *
 * Файлът е чист текст — без Supabase, без Resend, без "server-only" — за да го
 * четат тестовете и `scripts/preview-sequences.mts`. Изпращането е в
 * `lead-sequence.ts`.
 */

