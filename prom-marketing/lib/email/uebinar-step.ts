/**
 * Писмото-подарък с филма-уебинар „ВЪЛНАТА“ (Ивайло, 22.10.2026: „пусни го
 * направо като първи имейл — безплатен уебинар… лека-полека, като изненада“).
 *
 * Едно и също писмо в две поредици и с ЕДИН ключ (`UEBINAR_KEY`):
 *   • студената — първото писмо на всеки нов лийд (`lead-steps.ts`);
 *   • топлият кръг — първото от общия кръг (`warm-steps.ts`), тоест стига до
 *     всеки в кръга с неговото темпо, по най-много 25 на сутрин.
 * Ключът е общ нарочно: който го е получил като лийд, не го получава пак.
 *
 * Линкът е личен (`uebinarLink`) — влиза направо в залата, без формата, и
 * гледането се вписва в картона му.
 */
import { escapeHtml } from "./escape";
import { callout, cta, shell, signatureText, uebinarLink, type SequenceStep } from "./sequence-layout";

export const UEBINAR_KEY = "uebinar_valnata";

const SUBJECT = "Подарък за теб: филмът ни за AI (32 минути)";

export function uebinarStep(args: { afterDays: number; kind: "ПЪРВО" | "ПОДАРЪК"; firstTouch: boolean }): SequenceStep {
  return {
    key: UEBINAR_KEY,
    afterDays: args.afterDays,
    kind: args.kind,
    subject: SUBJECT,
    build: (name, ctx) => {
      const hi = name ? `Здравей, ${escapeHtml(name)},` : "Здравей,";
      const hiT = name ? `Здравей, ${name},` : "Здравей,";
      const intro = args.firstTouch
        ? "Благодаря, че се свърза с нас. Преди да се чуем, имам подарък за теб."
        : "Имам подарък за теб — без повод.";
      const link = uebinarLink(ctx);
      return {
        html: shell(
          `<p>${hi}</p>
<p>${intro}</p>
<p>Направихме филм за AI и българския бизнес — <strong>„ВЪЛНАТА“</strong>. 32 минути: защо изпуснахме компютрите, какво изпускаме сега с AI и какво може да направи една малка фирма още тази седмица.</p>
${cta(link, "Гледай филма →")}
<p style="color:#4a5651;margin-top:-8px;font-size:14px">Линкът е твой — влизаш направо, без регистрация, и продължаваш оттам, докъдето си стигнал.</p>
<p>Като го изгледаш, отговори ми с едно изречение: кое ти направи най-силно впечатление? Чета всичко лично.</p>
${callout("Честно отпред: филмът е направен изцяло с AI — дори гласът. Точно това е и темата му.")}`,
          ctx
        ),
        text: `${hiT}

${intro}

Направихме филм за AI и българския бизнес — „ВЪЛНАТА“. 32 минути: защо изпуснахме компютрите, какво изпускаме сега с AI и какво може да направи една малка фирма още тази седмица.

Гледай филма: ${link}
Линкът е твой — влизаш направо, без регистрация, и продължаваш оттам, докъдето си стигнал.

Като го изгледаш, отговори ми с едно изречение: кое ти направи най-силно впечатление? Чета всичко лично.

Честно отпред: филмът е направен изцяло с AI — дори гласът. Точно това е и темата му.

${signatureText(ctx)}`,
      };
    },
  };
}
