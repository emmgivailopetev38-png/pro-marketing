/**
 * Пълният ред писма за един човек: първо пътеката му, после общия кръг.
 * Ключовете са уникални, така че смяна на пътеката по средата просто вмъква
 * новите писма — нищо вече изпратено не се повтаря.
 */
export function warmStepsFor(track: WarmTrack): SequenceStep[] {
  return [...WARM_TRACKS[track], ...WARM_SEQUENCE];
}

/** Всички писма от топлия кръг, без повторения — за проверки и преглед. */
export const ALL_WARM_STEPS: SequenceStep[] = [
  ...TRACK_GOVORILI,
  ...TRACK_PREZENTACIA,
  ...TRACK_OFERTA,
  ...WARM_SEQUENCE,
];

/** Темата на стъпката за конкретния етап — писмата с два варианта я сменят. */
export function subjectFor(step: SequenceStep, ctx?: BuildCtx): string {
  return step.subjectFor ? step.subjectFor(ctx?.stage) : step.subject;
}
