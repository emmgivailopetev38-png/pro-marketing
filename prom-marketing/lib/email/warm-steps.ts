/**
 * Коя пътека получава човекът.
 *
 * Офертата е с предимство пред презентацията, тя — пред простия разговор.
 * `lost` и „незаинтересован" не влизат в пътека: човек, който е казал „не сега",
 * получава само общия кръг и то на половин темпо — виж `paceFor` в двигателя.
 * „Говорили сме" иска ИСТИНСКИ разговор или среща в картона (`talked`), не
 * етап: етапът „contacted" се слага и след наш имейл, а писмото започва с
 * „радвам се, че се чухме".
 */
export function trackFor(c: { stage: string; followup_status: string | null }, talked: boolean): WarmTrack {
  const fs = c.followup_status ?? "";
  if (c.stage === "lost" || fs === "not_interested") return "obshta";
  if (OFFER_STAGES.has(c.stage) || OFFER_STATUSES.has(fs)) return "oferta";
  if (PREZ_STAGES.has(c.stage) || PREZ_STATUSES.has(fs)) return "prezentacia";
  if (talked) return "govorili";
  return "obshta";
}

