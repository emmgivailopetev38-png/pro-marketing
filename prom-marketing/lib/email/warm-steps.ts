/** Етапите, в които човекът вече има оферта или презентация на масата. */
const LATE_STAGES = new Set(["presentation_sent", "offer_sent", "negotiating"]);

/** Оферта на масата — по етап или по статус на проследяване. */
const OFFER_STAGES = new Set(["offer_sent", "negotiating"]);
const OFFER_STATUSES = new Set(["sent_offer", "sent_proforma", "ready_to_close"]);

/** Презентация на масата. */
const PREZ_STAGES = new Set(["presentation_sent"]);
const PREZ_STATUSES = new Set(["sent_presentation"]);

function greeting(name: string | null): { hi: string; hiT: string } {
  return {
    hi: name ? `Здравей, ${escapeHtml(name)},` : "Здравей,",
    hiT: name ? `Здравей, ${name},` : "Здравей,",
  };
}

