/** Краят на последния прозорец: 30 мин след началото никой пост не е закъснял „навреме“. */
const KRAI = new Date("2026-11-29T19:30:00+02:00").getTime();

/**
 * Кой пост е дължим СЕГА: само последният, чийто час е минал, ако още не е
 * пуснат и следващият му час не е дошъл. Така пропуснат пост (Viber е бил
 * спрян, одобрението е дошло по-късно) тръгва веднага, но никога няколко
 * наведнъж.
 */
export function dalzhimiPostove(now: number, pusnati: ReadonlySet<string>): string[] {
  const t = (iso: string) => new Date(iso).getTime();
  let i = -1;
  for (let j = 0; j < VIBER_POSTOVE.length; j++) if (t(VIBER_POSTOVE[j].koga) <= now) i = j;
  if (i === -1) return [];
  const p = VIBER_POSTOVE[i];
  const sledvasht = VIBER_POSTOVE[i + 1];
  const do_ = sledvasht ? t(sledvasht.koga) : KRAI;
  if (now >= do_ || pusnati.has(p.kluch)) return [];
  return [p.kluch];
}

export function viberPostZa(kluch: string): ViberPost {
  const p = VIBER_POSTOVE.find((x) => x.kluch === kluch);
  if (!p) throw new Error(`Няма Viber пост ${kluch}`);
  return p;
}
