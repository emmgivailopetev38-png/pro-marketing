/** Краят на събитието (ISO) — за календарния линк. */
export function endISO(c: Pick<NaZhivo, "dateISO" | "durationMinutes"> = NA_ZHIVO): string {
  return new Date(new Date(c.dateISO).getTime() + c.durationMinutes * 60_000).toISOString();
}

function gcalStamp(iso: string): string {
  return new Date(iso).toISOString().replace(/[-:]/g, "").replace(/\.\d{3}Z$/, "Z");
}

/** Линк „Добави в Google Календар“ — без отделна страница за потвърждение. */
