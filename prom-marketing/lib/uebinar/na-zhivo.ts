/** Краят на събитието (ISO) — за календарния линк. */
export function endISO(c: Pick<NaZhivo, "dateISO" | "durationMinutes"> = NA_ZHIVO): string {
  return new Date(new Date(c.dateISO).getTime() + c.durationMinutes * 60_000).toISOString();
}

function gcalStamp(iso: string): string {
  return new Date(iso).toISOString().replace(/[-:]/g, "").replace(/\.\d{3}Z$/, "Z");
}

/** Линк „Добави в Google Календар“ — без отделна страница за потвърждение. */
export function calendarUrl(c: NaZhivo = NA_ZHIVO): string {
  const p = new URLSearchParams({
    action: "TEMPLATE",
    text: `Обучение на живо „${c.name}“ с ${c.host}`,
    dates: `${gcalStamp(c.dateISO)}/${gcalStamp(endISO(c))}`,
    details: `Безплатно онлайн обучение в ${c.platform}. Линкът идва на Viber, SMS и имейл в деня на обучението.`,
    ctz: "Europe/Sofia",
  });
  return `https://calendar.google.com/calendar/render?${p.toString()}`;
}

const DNI = ["Неделя", "Понеделник", "Вторник", "Сряда", "Четвъртък", "Петък", "Събота"];

/** Денят от седмицата на датата (по българско време) — за проверката в теста. */
export function denOtSedmicata(iso: string = NA_ZHIVO.dateISO): string {
  const d = new Intl.DateTimeFormat("en-US", { timeZone: "Europe/Sofia", weekday: "short" }).format(new Date(iso));
  const i = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"].indexOf(d);
  return DNI[i] ?? "";
}
