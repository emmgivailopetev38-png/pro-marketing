/** Въпросите, които влизат в процента (последният е за готовността). */
export const VAPROSI_ZA_PROCENT = VAPROSI.filter((v) => v.id !== "polzva");
export const MAKS_TOCHKI = VAPROSI_ZA_PROCENT.length * 3;

export type Rezultat = {
  procent: number;
  band: Band;
  kategorii: KategoriaId[];
  gotovnost: Gotovnost;
};

/** otgovori: id на въпроса → точките на избрания отговор. */
export function smetni(otgovori: Record<string, number>): Rezultat {
  const sbor = VAPROSI_ZA_PROCENT.reduce((s, v) => s + clamp(otgovori[v.id] ?? 0, 0, 3), 0);
  // Никоя работа не е 0 % или 100 % — показваме между 5 и 95.
  const procent = Math.max(5, Math.min(95, Math.round((sbor / MAKS_TOCHKI) * 100)));
  const band: Band = procent >= 65 ? "visoko" : procent >= 35 ? "sredno" : "nisko";
  const kategorii = VAPROSI_ZA_PROCENT.filter((v) => v.kategoria && (otgovori[v.id] ?? 0) >= 2)
    .sort((a, b) => (otgovori[b.id] ?? 0) - (otgovori[a.id] ?? 0))
    .map((v) => v.kategoria as KategoriaId);
  const p = otgovori.polzva ?? 0;
  const gotovnost: Gotovnost = p >= 3 ? "vseki-den" : p === 2 ? "ponyakoga" : p === 1 ? "probvah" : "ne";
  return { procent, band, kategorii, gotovnost };
}

function clamp(x: number, a: number, b: number) {
  return Math.max(a, Math.min(b, Number.isFinite(x) ? x : 0));
}

